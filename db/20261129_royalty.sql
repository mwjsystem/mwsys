-- =====================================================================
-- ロイヤリティ（現行の各団体のロイヤリティ Excel の置き換え）
--
--   msroyorg  : 団体（明細書の宛先・登録番号・振込先・担当・挨拶文）
--   msroyitem : 団体ごとの集計する商品（明細書の行）
--                 grp    区分（団体ごとの意味は画面の「ロイヤリティマスタ」の説明を見る）
--                 gcodes 商品コード。カンマ区切り。末尾の * は前方一致（例: KK-NG23*）。
--                        複数の行に当たるときは、いちばん長い（細かい）指定の行に入れる
--                 cond   条件（例: pcode:9 / region:北海道,沖縄県 / not:CBKK1BK* / chubunrui:013 / teika / oroshi）
--                 price〜price4・rate  単価・率（団体ごとの意味は画面の説明を見る）
--   msroymem  : 団体ごとの顧客（集計する納品先・支部・道場など）
--                 kind   種類（target 集計する納品先 / exclude 除く受注先 / dojo 新極真会の支部・道場 /
--                        branch 支部の道場（pcode の支部にまとめる）/ eda 本部の別納先 / kaigai 海外 /
--                        sheet・taikai JKJO の顧客ごとのシート / kansai・tabata・grachan 連合 など）
--                 seq    並び順（新極真会の月の明細の支部・道場の並び）
--                 aseq   年間集計表の並び（新極真会）
--
--   集計は画面（ロイヤリティ）で、受注伝票・受注明細を読んで行い、Excel を作る。DB に結果は残さない。
--
-- 適用方法: Hasura コンソール > Data > SQL で、search_path を test / public に切り替えて 1 回ずつ実行する。
--           もう一度実行すると、マスタは初期データに戻る（各団体の行を消して入れ直す）。
-- =====================================================================
SET search_path TO test;  -- 本番に適用するときは public に変更

CREATE TABLE IF NOT EXISTS msroyorg (
  id smallint NOT NULL,
  org text NOT NULL,
  seq integer NOT NULL DEFAULT 0,
  name text NOT NULL,
  dest text,
  dest2 text,
  regno text,
  bank text,
  bank2 text,
  tanto text,
  greet text,
  memo text,
  PRIMARY KEY (id, org)
);
COMMENT ON TABLE msroyorg IS 'ロイヤリティの団体';
COMMENT ON COLUMN msroyorg.org IS '団体のキー（プログラムの集計方法と対応。変えない）';
COMMENT ON COLUMN msroyorg.dest IS '宛先（改行で複数行）';
COMMENT ON COLUMN msroyorg.dest2 IS '2 つめの宛先（連合: 関西総本部）';
COMMENT ON COLUMN msroyorg.regno IS '登録番号の行';
COMMENT ON COLUMN msroyorg.bank IS '振込先・支払方法（改行で複数行）';
COMMENT ON COLUMN msroyorg.bank2 IS '2 つめの振込先（JKJO: JKC 事務局）';
COMMENT ON COLUMN msroyorg.tanto IS '担当者';
COMMENT ON COLUMN msroyorg.greet IS '挨拶文';

CREATE TABLE IF NOT EXISTS msroyitem (
  rid serial PRIMARY KEY,
  id smallint NOT NULL,
  org text NOT NULL,
  grp text,
  seq integer NOT NULL DEFAULT 0,
  name text,
  size text,
  color text,
  gcodes text,
  cond text,
  price numeric,
  price2 numeric,
  price3 numeric,
  price4 numeric,
  rate numeric,
  memo text
);
CREATE INDEX IF NOT EXISTS msroyitem_org ON msroyitem (id, org, seq);
COMMENT ON TABLE msroyitem IS 'ロイヤリティの集計する商品（明細書の行）';
COMMENT ON COLUMN msroyitem.grp IS '区分';
COMMENT ON COLUMN msroyitem.gcodes IS '商品コード（カンマ区切り。末尾 * は前方一致）';
COMMENT ON COLUMN msroyitem.cond IS '条件';

CREATE TABLE IF NOT EXISTS msroymem (
  rid serial PRIMARY KEY,
  id smallint NOT NULL,
  org text NOT NULL,
  kind text NOT NULL,
  seq integer NOT NULL DEFAULT 0,
  aseq integer,
  mcode text,
  eda text,
  pcode text,
  name text,
  memo text
);
CREATE INDEX IF NOT EXISTS msroymem_org ON msroymem (id, org, kind, seq);
COMMENT ON TABLE msroymem IS 'ロイヤリティの顧客（集計する納品先・支部・道場など）';
COMMENT ON COLUMN msroymem.kind IS '種類';
COMMENT ON COLUMN msroymem.aseq IS '年間集計表の並び（新極真会）';
COMMENT ON COLUMN msroymem.eda IS '納品先の枝番';
COMMENT ON COLUMN msroymem.pcode IS 'まとめる先の顧客コード（新極真会: 道場 → 支部）';

DELETE FROM msroyorg WHERE id = 1;
DELETE FROM msroyitem WHERE id = 1;
DELETE FROM msroymem WHERE id = 1;

