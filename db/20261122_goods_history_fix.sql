-- =====================================================================
-- 商品マスタの履歴の直し（保存し直しただけで「0→(空)」の履歴がたくさん出た）
--
--   原因: 商品マスタの画面の保存が、単価・原価の 0 を空（NULL）にして書いていた（アプリは直した）。
--         トリガーはそれを変更として記録していた。
--   直し: トリガーで、数の列は 空 と 0（8250 と 8250.00 も）を同じとみなす。
--
-- 適用方法:
--   1. db/20261121_goods_history.sql をもう一度、test / public で流す（何度流しても大丈夫。トリガーの関数が新しくなる）
--   2. 下の 3・4 で、もう出てしまった「0→(空)」だけの履歴を消す（任意。先に 3 で中身を確かめる）
--   3・4 は search_path を test / public に切り替えて流す
-- =====================================================================
SET search_path TO test;  -- 本番に適用するときは public に変更

-- 3. 消す履歴を確かめる（「変更:」の中身が全部「… 0→(空)」「… (空)→0」のもの）
SELECT sequ, keycode, created_at, memo
  FROM tropelog
 WHERE extype = '14' AND memo LIKE '% 変更: %'
   AND regexp_replace(substring(memo FROM ' 変更: (.*)$'),
                      '[^,]*? (0(\.0+)?→\(空\)|\(空\)→0(\.0+)?)(, )?', '', 'g') = ''
 ORDER BY sequ;

-- 4. 消す
DELETE FROM tropelog
 WHERE extype = '14' AND memo LIKE '% 変更: %'
   AND regexp_replace(substring(memo FROM ' 変更: (.*)$'),
                      '[^,]*? (0(\.0+)?→\(空\)|\(空\)→0(\.0+)?)(, )?', '', 'g') = '';
